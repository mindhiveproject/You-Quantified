import { findDeviceByName } from "../../../devices/definitions";
import React from "react";
import { ModalDataInformation } from "./data_sources_display";
import { VideoInfoPane } from "./video_generic";

export function LeftInfoPane({ currentDevice, leftPaneInfoRef }) {
  return (
    <div className="w-100 h-100 ms-3 pe-4-5 mb-5">
      {currentDevice?.card_type === "generic" && (
        <div
          className="card rounded-0 text-start black-hover border-dark"
          ref={leftPaneInfoRef}
        >
          <GenericInfoPane currentDevice={currentDevice} />
        </div>
      )}
      {currentDevice?.card_type === "upload" && (
        <div className="card rounded-0 text-start black-hover border-dark">
          <UploadInfoPane />
        </div>
      )}
      {currentDevice?.card_type === "video" && (
        <div className="card rounded-0 text-start black-hover border-dark">
          <VideoInfoPane currentDevice={currentDevice} />
        </div>
      )}
    </div>
  );
}

function GenericInfoPane({ currentDevice }) {
  const deviceInfo = findDeviceByName(currentDevice?.device);

  return (
    <div className="p-4">
      <h4 className="mb-2">{deviceInfo.name}</h4>
      <div>
        <span>{deviceInfo.description}</span>
        <div className="mt-3">
          <h6>Available data streams</h6>
          <p>
            This device can stream the following data to a visualization. Hover
            to learn more.
          </p>
          <ModalDataInformation source={deviceInfo.name} groupData={true} />
        </div>
      </div>
    </div>
  );
}

function UploadInfoPane() {
  return (
    <div className="p-4">
      <h4 className="mb-2">Upload Your Recording</h4>
      <div>
        <p>
          Upload a .zip file of a recording generated by this app. Recordings
          made before the yq-data update are converted when they load.
        </p>
        <div className="mt-3">
          <h6>Note</h6>
          <p>
            Uploaded files are not sent to any servers and will remain on your
            computer.
          </p>
        </div>
        <div className="mt-3">
          <h6>Available data streams</h6>
          <p>
            The data streams available for analysis will depend on the devices
            you used during the recording.
          </p>
        </div>
      </div>
    </div>
  );
}
